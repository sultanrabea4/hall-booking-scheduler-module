    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        // TODO add your handling code here:
        
       // File handling: Load the hall data from view_halls.txt when the form opens
    File file = new File("view_halls.txt");

    // Check if the file exists before reading
    if (file.exists()) {
        try {
            // Use BufferedReader to read the file line by line
            BufferedReader br = new BufferedReader(new FileReader(file));
            String line;

            // Get the table model to add rows
            DefaultTableModel model = (DefaultTableModel) HallsTable.getModel();

            // Read each line from the file
            while ((line = br.readLine()) != null) {
                // Assuming the format of each line is like: "Hall ID: H001, Hall Type: Conference, Booking Rate: 100, Capacity: 50"
                String[] hallData = line.split(", "); // Split the line by comma and space

                // Extract the individual pieces of data from the split result
                String hallId = hallData[0].split(": ")[1]; // Extract the part after "Hall ID: "
                String hallType = hallData[1].split(": ")[1]; // Extract the part after "Hall Type: "
                String bookingRate = hallData[2].split(": ")[1]; // Extract the part after "Booking Rate: "
                String capacity = hallData[3].split(": ")[1]; // Extract the part after "Capacity: "

                // Add a new row to the table with the hall data
                model.addRow(new Object[]{hallId, hallType, bookingRate, capacity});
            }

            // Close the BufferedReader
            br.close();
        } catch (IOException e) {
            // Handle file reading errors
            JOptionPane.showMessageDialog(this,
                    "Error reading file: " + e.getMessage(),
                    "File Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    } else {
        // File doesn't exist yet, show a message if needed (optional)
        System.out.println("No saved hall data found.");
    }
    }//GEN-LAST:event_formWindowOpened

    private void EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditActionPerformed
        // TODO add your handling code here:
        int row = HallsTable.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this,
                "No row is selected! Please select one row to edit.",
                "Select Row",
                JOptionPane.ERROR_MESSAGE);
        } else {
            // Retrieve original hall data from the table (before edit)
            DefaultTableModel model = (DefaultTableModel) HallsTable.getModel();
            String originalHallId = model.getValueAt(row, 0).toString();
            String originalHalltype = model.getValueAt(row, 1).toString();
            String originalBookingrate = model.getValueAt(row, 2).toString();
            String originalCapacity = model.getValueAt(row, 3).toString();

            // Get the new edited values from the input fields
            String newHallId = hallidtext.getText();
            String newHalltype = halltepytext.getText();
            String newBookingrate = bookingratetext.getText();
            String newCapacity = capacitytext.getText();

            // Check if all fields are filled
            if (newHallId.isEmpty() || newHalltype.isEmpty() || newBookingrate.isEmpty() || newCapacity.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                    "Please fill in all fields to update the hall details.",
                    "Incomplete Input",
                    JOptionPane.ERROR_MESSAGE);
            } else {
                // Update the table with the new data
                model.setValueAt(newHallId, row, 0);
                model.setValueAt(newHalltype, row, 1);
                model.setValueAt(newBookingrate, row, 2);
                model.setValueAt(newCapacity, row, 3);

                // Now update the corresponding entry in the file
                File file = new File("view_halls.txt");
                if (file.exists()) {
                    try {
                        // Step 1: Read all lines from the file into a list
                        ArrayList<String> hallList = new ArrayList<>();
                        BufferedReader br = new BufferedReader(new FileReader(file));
                        String line;

                        // Read each line and modify the matching one
                        while ((line = br.readLine()) != null) {
                            if (line.equals("Hall ID: " + originalHallId + ", Hall Type: " + originalHalltype +
                                ", Booking Rate: " + originalBookingrate + ", Capacity: " + originalCapacity)) {
                            // Replace the old line with the new edited data
                            hallList.add("Hall ID: " + newHallId + ", Hall Type: " + newHalltype +
                                ", Booking Rate: " + newBookingrate + ", Capacity: " + newCapacity);
                        } else {
                            hallList.add(line); // Keep non-matching lines as they are
                        }
                    }
                    br.close();

                    // Step 2: Write the updated list back to the file
                    BufferedWriter bw = new BufferedWriter(new FileWriter(file));
                    for (String hall : hallList) {
                        bw.write(hall);
                        bw.newLine();
                    }
                    bw.close();

                    JOptionPane.showMessageDialog(this,
                        "Hall updated successfully!",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);
                } catch (IOException e) {
                    JOptionPane.showMessageDialog(this,
                        "Error updating the file: " + e.getMessage(),
                        "File Error",
                        JOptionPane.ERROR_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this,
                    "File not found!",
                    "File Error",
                    JOptionPane.ERROR_MESSAGE);
            }

            // Clear the input fields after editing
            hallidtext.setText("");
            halltepytext.setText("");
            bookingratetext.setText("");
            capacitytext.setText("");
        }
        }
    }//GEN-LAST:event_EditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = HallsTable.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this,
                "No row is selected! Please select one row.",
                "Select Row",
                JOptionPane.ERROR_MESSAGE);
        } else {
            // Remove from the table model
            DefaultTableModel model = (DefaultTableModel) HallsTable.getModel();

            // Get the hall details from the selected row (assuming correct column order)
            String HallId = model.getValueAt(row, 0).toString();
            String Halltype = model.getValueAt(row, 1).toString();
            String bookingrate = model.getValueAt(row, 2).toString();
            String capacity = model.getValueAt(row, 3).toString();

            // Remove the row from the table
            model.removeRow(row);

            // File handling: Remove the corresponding entry from the file
            File file = new File("view_halls.txt");
            if (file.exists()) {
                try {
                    // Step 1: Read all lines from the file into a list, skipping the one to delete
                    ArrayList<String> hallList = new ArrayList<>();
                    BufferedReader br = new BufferedReader(new FileReader(file));
                    String line;

                    // Read each line and add to the list unless it matches the selected hall
                    while ((line = br.readLine()) != null) {
                        if (!line.equals("Hall ID: " + HallId + ", Hall Type: " + Halltype +
                            ", Booking Rate: " + bookingrate + ", Capacity: " + capacity)) {
                        hallList.add(line); // Keep only non-matching lines
                    }
                }
                br.close();

                // Step 2: Write the updated list back to the file
                BufferedWriter bw = new BufferedWriter(new FileWriter(file));
                for (String hall : hallList) {
                    bw.write(hall);
                    bw.newLine();
                }
                bw.close();

                JOptionPane.showMessageDialog(this,
                    "Hall deleted successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this,
                    "Error deleting from file: " + e.getMessage(),
                    "File Error",
                    JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this,
                "File not found!",
                "File Error",
                JOptionPane.ERROR_MESSAGE);
        }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

