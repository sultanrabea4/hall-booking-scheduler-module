    // Utility method to extract the value after the colon (":")
       private String extractValue(String data) {
    if (data.contains(":")) {
        return data.split(":")[1].trim(); // Extract the value part and trim spaces
    }
    return data.trim(); // In case there's no colon, return the data as is
}

    
    
    
    private void loadMaintenanceData() {
   File file = new File("maintenance_schedule.txt");

    if (file.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel(); // Add this line here
            model.setRowCount(0); // Clear existing rows

            while ((line = br.readLine()) != null) {
                String[] data = line.split(", ");
                model.addRow(data); // Add rows to the model
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }
    
   private void saveToFile() {
   try (BufferedWriter bw = new BufferedWriter(new FileWriter("maintenance_schedule.txt"))) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel(); // Add this line here
        
        for (int i = 0; i < model.getRowCount(); i++) {
            String hallId = model.getValueAt(i, 0).toString();
            String startDate = model.getValueAt(i, 1).toString();
            String startTime = model.getValueAt(i, 2).toString();
            String endDate = model.getValueAt(i, 3).toString();
            String endTime = model.getValueAt(i, 4).toString();
            String remarks = model.getValueAt(i, 5).toString();

            bw.write(hallId + ", " + startDate + ", " + startTime + ", " + endDate + ", " + endTime + ", " + remarks);
            bw.newLine();
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error saving data: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
    }
    }
    
   
