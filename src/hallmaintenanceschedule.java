    private void SearchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchButtonActionPerformed
        // TODO add your handling code here:
         String searchHallId = SearchFiled.getText().trim();
    
    if (searchHallId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a Hall ID.", "Input Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    boolean hallFound = false;
    File viewHallsFile = new File("view_halls.txt");

    if (viewHallsFile.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(viewHallsFile))) {
            String line;
            while ((line = br.readLine()) != null) {
                if (line.contains("Hall ID: " + searchHallId)) {
                    hallFound = true;
                    JOptionPane.showMessageDialog(this, "Hall ID found: " + searchHallId, "Success", JOptionPane.INFORMATION_MESSAGE);
                    enableFields(true); // Enable fields for data entry
                    return;
                }
            }

            if (!hallFound) {
                JOptionPane.showMessageDialog(this, "Hall ID not found in view_halls.txt!", "Not Found", JOptionPane.ERROR_MESSAGE);
                enableFields(false);
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "view_halls.txt file not found!", "File Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_SearchButtonActionPerformed

    private void AddButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddButtonActionPerformed
        // TODO add your handling code here:
        
        try {
        // Gather input data from form fields
        String hallId = SearchFiled.getText().trim();
        String startDate = StartDateField.getText().trim();
        String startTime = StartTimeField.getText().trim();
        String endDate = EndDateField.getText().trim();
        String endTime = EndTimeFiled.getText().trim();
        String remarks = RemarksField.getText().trim();

        // Check if required fields are filled
        if (hallId.isEmpty() || startDate.isEmpty() || startTime.isEmpty() || endDate.isEmpty() || endTime.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all required fields", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate date and time formats
        if (!startDate.matches("\\d{2}/\\d{2}/\\d{4}") || !endDate.matches("\\d{2}/\\d{2}/\\d{4}")) {
            JOptionPane.showMessageDialog(this, "Please enter the date in DD/MM/YYYY format", "Invalid Date Format", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!startTime.matches("\\d{2}:\\d{2}") || !endTime.matches("\\d{2}:\\d{2}")) {
            JOptionPane.showMessageDialog(this, "Please enter the time in HH:mm format", "Invalid Time Format", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Convert start and end dates to Date objects for comparison
        SimpleDateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy");
        Date maintenanceStartDate;
        Date maintenanceEndDate;
        try {
            maintenanceStartDate = dateFormat.parse(startDate);
            maintenanceEndDate = dateFormat.parse(endDate);
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(this, "Invalid date format", "Date Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Check for conflicts in availability_schedule.txt
        boolean conflictFound = false;
        File availabilityFile = new File("availability_schedule.txt");

        if (availabilityFile.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(availabilityFile))) {
                String line;
                while ((line = br.readLine()) != null) {
                    String[] data = line.split(", ");
                    if (data.length >= 5) {
                        String fileHallId = extractValue(data[0]);
                        String fileStartDate = extractValue(data[4]);
                        String fileEndDate = extractValue(data[6]);

                        // Convert file dates to Date objects
                        Date fileStartDateObj = dateFormat.parse(fileStartDate);
                        Date fileEndDateObj = dateFormat.parse(fileEndDate);

                        // Check if the Hall ID matches and dates overlap
                        if (fileHallId.equals(hallId) && 
                            ((maintenanceStartDate.compareTo(fileStartDateObj) >= 0 && maintenanceStartDate.compareTo(fileEndDateObj) <= 0) ||
                             (maintenanceEndDate.compareTo(fileStartDateObj) >= 0 && maintenanceEndDate.compareTo(fileEndDateObj) <= 0) ||
                             (maintenanceStartDate.compareTo(fileStartDateObj) <= 0 && maintenanceEndDate.compareTo(fileEndDateObj) >= 0))) {
                            conflictFound = true;
                            JOptionPane.showMessageDialog(this, "The Hall Is Available IN This Date , Choose Another Date", "Date Conflict", JOptionPane.ERROR_MESSAGE);
                            return;
                        }
                    }
                }
            } catch (IOException | ParseException e) {
                JOptionPane.showMessageDialog(this, "Error checking availability: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        // No conflict found, add the data
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.addRow(new Object[]{hallId, startDate, startTime, endDate, endTime, remarks});

        // Save to maintenance_schedule.txt
        File maintenanceFile = new File("maintenance_schedule.txt");
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(maintenanceFile, true))) {
            bw.write(hallId + ", " + startDate + ", " + startTime + ", " + endDate + ", " + endTime + ", " + remarks);
            bw.newLine();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving data: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }

        clearFields();
        JOptionPane.showMessageDialog(this, "Maintenance record added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_AddButtonActionPerformed

    private void EditButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "Please select a row to edit.", "No Selection", JOptionPane.ERROR_MESSAGE);
        return;
    }

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setValueAt(SearchFiled.getText().trim(), selectedRow, 0);
    model.setValueAt(StartDateField.getText().trim(), selectedRow, 1);
    model.setValueAt(StartTimeField.getText().trim(), selectedRow, 2);
    model.setValueAt(EndDateField.getText().trim(), selectedRow, 3);
    model.setValueAt(EndTimeFiled.getText().trim(), selectedRow, 4);
    model.setValueAt(RemarksField.getText().trim(), selectedRow, 5);

    saveToFile(); // Save changes to the file
    clearFields();
    JOptionPane.showMessageDialog(this, "Maintenance record updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_EditButtonActionPerformed

