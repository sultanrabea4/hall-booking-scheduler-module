    private void EditButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditButtonActionPerformed
        // TODO add your handling code here:
         // Get the selected row from the table
    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "No row is selected! Please select a row to edit.", "Select Row", JOptionPane.ERROR_MESSAGE);
    } else {
        // Get the current values of the selected row
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        
        // If the input field is not empty, use the new value, otherwise keep the old value
        String hallId = HallIDField.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 0).toString() : HallIDField.getText().trim();
        String startDate = StartDateField.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 1).toString() : StartDateField.getText().trim();
        String startTime = StartTimeField.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 2).toString() : StartTimeField.getText().trim();
        String endDate = EndDateField.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 3).toString() : EndDateField.getText().trim();
        String endTime = EndTimeField.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 4).toString() : EndTimeField.getText().trim();
        String remarks = remaeks.getText().trim().isEmpty() ? model.getValueAt(selectedRow, 5).toString() : remaeks.getText().trim();

        // Update the selected row in the table with the new or old values
        model.setValueAt(hallId, selectedRow, 0);
        model.setValueAt(startDate, selectedRow, 1);
        model.setValueAt(startTime, selectedRow, 2);
        model.setValueAt(endDate, selectedRow, 3);
        model.setValueAt(endTime, selectedRow, 4);
        model.setValueAt(remarks, selectedRow, 5);

        // Rewrite the entire "availability_schedule.txt" file to reflect the updated data
        File file = new File("availability_schedule.txt");
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(file))) {
            for (int i = 0; i < model.getRowCount(); i++) {
                String id = model.getValueAt(i, 0).toString();
                String sDate = model.getValueAt(i, 1).toString();
                String sTime = model.getValueAt(i, 2).toString();
                String eDate = model.getValueAt(i, 3).toString();
                String eTime = model.getValueAt(i, 4).toString();
                String rem = model.getValueAt(i, 5).toString();
                bw.write(id + ", " + sDate + ", " + sTime + ", " + eDate + ", " + eTime + ", " + rem);
                bw.newLine();
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error updating file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }

        // Optionally: Clear the input fields after editing
        HallIDField.setText("");
        StartDateField.setText("");
        StartTimeField.setText("");
        EndDateField.setText("");
        EndTimeField.setText("");
        remaeks.setText("");  // Clear remarks field

        JOptionPane.showMessageDialog(this, "Row updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_EditButtonActionPerformed

    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        // TODO add your handling code here:
        // Get the selected row from the table
    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "No row is selected! Please select a row to delete.", "Select Row", JOptionPane.ERROR_MESSAGE);
    } else {
        // Remove the selected row from the table
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.removeRow(selectedRow);

        // Now rewrite the entire "availability_schedule.txt" file without the deleted row
        File file = new File("availability_schedule.txt");
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(file))) {
            // Loop through the remaining rows in the table and write them back to the file
            for (int i = 0; i < model.getRowCount(); i++) {
                String hallId = model.getValueAt(i, 0).toString();
                String startDate = model.getValueAt(i, 1).toString();
                String startTime = model.getValueAt(i, 2).toString();
                String endDate = model.getValueAt(i, 3).toString();
                String endTime = model.getValueAt(i, 4).toString();
                String remarks = model.getValueAt(i, 5).toString();
                
                bw.write(hallId + ", " + startDate + ", " + startTime + ", " + endDate + ", " + endTime + ", " + remarks);
                bw.newLine(); // Add a new line for each remaining row
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error updating the file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }

        // Optionally: Show a confirmation message
        JOptionPane.showMessageDialog(this, "Selected availability entry deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_deleteButtonActionPerformed

