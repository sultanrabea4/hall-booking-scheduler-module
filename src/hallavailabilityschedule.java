 private void loadAvailabilitySchedule() {
    File file = new File("availability_schedule.txt");

    if (file.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows

            while ((line = br.readLine()) != null) {
                System.out.println("Raw line: " + line); // Debugging line
                String[] data = line.split(", ");
                System.out.println("Field count: " + data.length); // Debugging line

                // Extract hallId, startDate, startTime, endDate, endTime
                if (data.length >= 5) {
                    String hallId = extractValue(data[0]);     // Extract Hall ID
                    String startDate = extractValue(data[1]);  // Extract Start Date
                    String startTime = extractValue(data[2]);  // Extract Start Time
                    String endDate = extractValue(data[3]);    // Extract End Date
                    String endTime = extractValue(data[4]);    // Extract End Time
                    String remarks = (data.length >= 6) ? extractValue(data[5]) : ""; // Extract Remarks or set empty if not present

                    model.addRow(new Object[]{hallId, startDate, startTime, endDate, endTime, remarks});
                } else {
                    String errorDetails = "Expected at least 5 fields but found " + data.length + " fields.\nLine content: " + line;
                    JOptionPane.showMessageDialog(this, "Invalid data format detected in availability_schedule.txt:\n" + errorDetails, "Data Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error loading availability schedule: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "availability_schedule.txt file not found!", "File Error", JOptionPane.ERROR_MESSAGE);
    }
}


// Utility method to extract the value after the colon (":")
private String extractValue(String data) {
    if (data.contains(":")) {
        return data.split(":")[1].trim(); // Extract the value part and trim spaces
    }
    return data.trim(); // In case there's no colon, return the data as is
}





